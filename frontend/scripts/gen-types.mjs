// Generates src/shared/api/schema.d.ts from openapi.json (dumped by backend/scripts/dump_openapi.py).
// `--check` regenerates in memory and fails when the checked-in file differs (run in CI).
import { readFileSync, writeFileSync } from "node:fs";
import openapiTS, { astToString } from "openapi-typescript";

const source = new URL("../openapi.json", import.meta.url);
const target = new URL("../src/shared/api/schema.d.ts", import.meta.url);
const header = "/* Generated by scripts/gen-types.mjs from openapi.json. Do not edit; run `npm run gen:types`. */\n";
const next = header + astToString(await openapiTS(JSON.parse(readFileSync(source, "utf8"))));

if (process.argv.includes("--check")) {
  const current = readFileSync(target, "utf8");
  if (current !== next) {
    console.error("schema.d.ts is out of date: run `npm run gen:openapi && npm run gen:types`");
    process.exit(1);
  }
  console.log("schema.d.ts is up to date");
} else {
  writeFileSync(target, next);
  console.log("wrote src/shared/api/schema.d.ts");
}
