"""Run a case set through `ask()` (the same path as `POST /api/analyst/ask`: render_fact display) and report.

Several runs of the same set are aggregated per metric (mean, min, max) and per case (k of N runs); the report records
the prompt fingerprint so a held-out run can be shown to use the unchanged prompts of the tuning run.
"""
import hashlib
from datetime import date
from decimal import ROUND_HALF_EVEN, Decimal

from app.analyst.harness import DRAFT_SYSTEM, PLAN_SYSTEM
from app.analyst.service import ask
from app.api.display import render_fact
from tests.analyst_eval.golden import CASES, DOCS, FACTS, Case
from tests.analyst_eval.scorer import Result, score, summary
from tests.analyst_support import D, USER, FakeRetriever, FakeTools

METRICS = (  # summary key -> report label
    ("routing_ok", "routing accuracy"), ("verified", "verified"), ("faithful", "number faithfulness"),
    ("semantic_ok", "semantic guard clean"), ("fallbacks", "fallbacks"), ("model_calls", "model calls"),
    ("input_tokens", "input tokens"), ("output_tokens", "output tokens"),
    ("mean_tokens_per_answer", "mean tokens per answer"),
    ("mean_tokens_per_model_answer", "mean tokens per answer that called the model"),
    ("max_tokens_per_answer", "max tokens per answer"),
)


def prompt_fingerprint() -> str:
    return hashlib.sha256((PLAN_SYSTEM + "\n" + DRAFT_SYSTEM).encode()).hexdigest()[:12]


def run_case(case: Case, llm) -> Result:
    tools = FakeTools(FACTS)
    retriever = FakeRetriever([DOCS[d] for d in case.docs])
    answer = ask(USER, case.question, D, llm=llm, tools=tools, retriever=retriever, render=render_fact)
    return score(case, answer, D)


def run(llm, cases=CASES) -> list[Result]:
    return [run_case(c, llm) for c in cases]


def _mean(values: list[int]) -> str:
    return str((Decimal(sum(values)) / Decimal(len(values))).quantize(Decimal("0.1"), rounding=ROUND_HALF_EVEN))


def aggregate(runs: list[list[Result]]) -> dict[str, dict]:
    """metric -> {"mean": text with one decimal, "min": int, "max": int} over the runs."""
    summaries = [summary(r) for r in runs]
    return {key: {"mean": _mean([s[key] for s in summaries]), "min": min(s[key] for s in summaries),
                  "max": max(s[key] for s in summaries)} for key, _ in METRICS}


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "/")[:220]


def report_runs(runs: list[list[Result]], *, title: str, model: str, run_date: date, set_name: str) -> str:
    n_runs, n = len(runs), len(runs[0])
    agg = aggregate(runs)
    lines = [
        f"# {title}",
        "",
        f"Date: {run_date.isoformat()}. Model: `{model}`. Set: {set_name} ({n} cases). runs: {n_runs}. "
        f"prompt fingerprint: `{prompt_fingerprint()}`.",
        "Generated by `backend/scripts/eval_analyst.py`; numbers are from the runs, not edited. Counts are per run "
        f"(out of {n} cases).",
        "",
        "## Summary",
        "",
        "| metric | mean | min | max |",
        "|---|---|---|---|",
    ]
    lines += [f"| {label} | {agg[key]['mean']} | {agg[key]['min']} | {agg[key]['max']} |" for key, label in METRICS]
    lines += [
        "",
        f"## Cases (k/{n_runs} = runs where it held; answer from the last run)",
        "",
        "| id | category | routing ok | verified | faithful | semantic clean | fallbacks | mean tokens | problems | "
        "last repair errors | answer |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for i in range(n):
        per = [r[i] for r in runs]
        last = per[-1]
        problems = sorted({p for r in per for p in (*r.problems, *r.semantic)})
        errors = sorted({e for r in per for e in r.answer.provenance["last_errors"] if r.answer.provenance["fallback"]})
        lines.append(
            f"| {last.case.id} | {last.case.category} | {sum(r.routing_ok for r in per)}/{n_runs} | "
            f"{sum(r.answer.verified for r in per)}/{n_runs} | {sum(r.faithful for r in per)}/{n_runs} | "
            f"{sum(r.semantic_ok for r in per)}/{n_runs} | "
            f"{sum(r.answer.provenance['fallback'] == 'template' for r in per)}/{n_runs} | "
            f"{_mean([r.tokens for r in per])} | {_cell('; '.join(problems)) or '-'} | "
            f"{_cell('; '.join(errors)) or '-'} | {_cell(last.answer.text)} |")
    return "\n".join(lines) + "\n"


def report(results: list[Result], *, title: str, model: str, run_date: date, set_name: str = "tuning") -> str:
    return report_runs([results], title=title, model=model, run_date=run_date, set_name=set_name)
